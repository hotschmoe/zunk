const std = @import("std");
const wa = @import("wasm_analyze.zig");
const resolver = @import("js_resolve.zig");
const source_map = @import("source_map.zig");

pub const BridgeJsChunk = struct {
    /// Human-readable label printed into the merged JS as a banner comment
    /// (e.g. `bridge.js`, `js/bridge.js`, or a dep package directory name).
    origin: []const u8,
    source: []const u8,
};

/// A web font the page must have loaded before the app starts. The file
/// lives at `<public_url>fonts/<file>` (copied there by `zunk build`).
pub const FontFace = struct {
    family: []const u8,
    /// CSS `font-weight` (400 regular, 500 medium, 700 bold, ...).
    weight: u16,
    /// Basename of the font file inside `fonts/`.
    file: []const u8,
};

pub const GenOptions = struct {
    public_url: []const u8 = "/",
    wasm_filename: []const u8,
    /// Concatenated in order. Convention: dep-provided chunks first, user's
    /// own project chunk last, so the user can override symbols from deps.
    bridge_js_chunks: []const BridgeJsChunk = &.{},
    js_filename: []const u8 = "app.js",
    wasm_preload: bool = false,
    /// `@font-face` rules go into the page; the app starts only after every
    /// face has loaded (`document.fonts.load`), so the first text measurement
    /// already sees the real font.
    fonts: []const FontFace = &.{},
    js_integrity: ?[]const u8 = null,
    verbose_report: bool = false,
    json_report: bool = false,
};

pub const Categories = std.enums.EnumSet(resolver.Category);

pub const GenResult = struct {
    js: []const u8,
    /// Source Map v3 JSON, or empty if no mappable content was emitted
    /// (currently: empty when there are no bridge.js chunks). When empty,
    /// callers should skip writing a .js.map file.
    js_map: []const u8,
    html: []const u8,
    report: []const u8,
    js_hash: [16]u8,
    categories: Categories,

    pub fn deinit(self: *GenResult, allocator: std.mem.Allocator) void {
        allocator.free(self.js);
        if (self.js_map.len != 0) allocator.free(self.js_map);
        allocator.free(self.html);
        allocator.free(self.report);
    }
};

pub fn generate(
    allocator: std.mem.Allocator,
    analysis: *const wa.Analysis,
    opts: GenOptions,
) !GenResult {
    var resolutions = try allocator.alloc(resolver.Resolution, analysis.imports.len);
    defer {
        for (resolutions) |*r| allocator.free(r.js_body);
        allocator.free(resolutions);
    }

    var needs = Features{};
    var categories_used = Categories.empty;
    var stub_count: usize = 0;

    for (analysis.imports, 0..) |*imp, i| {
        const sig = analysis.getImportSignature(imp);
        resolutions[i] = try resolver.resolve(allocator, imp, sig);
        const r = &resolutions[i];

        if (r.needs_handles) needs.handles = true;
        if (r.needs_string_helper) needs.strings = true;
        if (r.needs_callbacks) needs.callbacks = true;
        if (r.needs_memory_view) needs.memory_view = true;
        categories_used.insert(r.category);
        if (r.confidence == .stub) stub_count += 1;
    }

    const has_init = analysis.hasExport("init");
    const has_frame = analysis.hasExport("frame");
    const has_resize = analysis.hasExport("resize");
    const has_cleanup = analysis.hasExport("cleanup");

    if (has_frame) needs.render_loop = true;
    if (has_resize) needs.resize_handler = true;
    if (categories_used.contains(.input)) needs.input_system = true;
    if (categories_used.contains(.audio)) needs.audio_state = true;
    if (categories_used.contains(.webgpu)) needs.webgpu_init = true;
    if (categories_used.contains(.ui)) needs.ui_system = true;
    if (categories_used.contains(.a11y)) needs.a11y_state = true;
    if (categories_used.contains(.fx)) needs.fx = true;
    if (categories_used.contains(.ime)) needs.ime = true;

    var js_aw: std.Io.Writer.Allocating = .init(allocator);
    defer js_aw.deinit();
    const w = &js_aw.writer;

    try w.writeAll("// Generated by zunk -- do not edit.\n");
    try w.writeAll("// https://github.com/hotschmoe/zunk\n\n");

    try w.writeAll("(async function() {\n'use strict';\n\n");

    if (needs.handles) try emitHandleTable(w);
    if (needs.strings) try emitStringHelper(w);
    if (needs.audio_state) try emitAudioState(w);
    if (needs.input_system) try emitInputSystem(w);
    if (needs.webgpu_init) try emitWebGPUState(w);
    if (categories_used.contains(.fetch)) try w.writeAll("let zunkFetchBuf = null;\n\n");
    if (needs.ui_system) try emitUISystem(w);
    if (needs.a11y_state) try emitA11yState(w);
    if (needs.fx) try w.writeAll(fx_js ++ "\n\n");
    if (needs.ime) try w.writeAll(ime_js ++ "\n\n");

    // Mutable WASM bindings. Held at module scope so that HMR can swap the
    // underlying instance while env methods (which close over this scope
    // and resolve these names at call time) transparently retarget.
    try w.writeAll("let instance, exports, memory;\n\n");

    try w.writeAll("const env = {\n");

    for (analysis.imports, 0..) |*imp, i| {
        const r = &resolutions[i];

        if (!std.mem.eql(u8, imp.module, "env")) continue;
        try w.print("  {s}() {{ {s} }},\n", .{ imp.name, r.js_body });
    }

    try w.writeAll("};\n\n");

    // Record byte spans of bridge.js content so the source map can point
    // back at the original library-provided JS. Span is [start, end) and
    // covers only the chunk body (not the banner comment or trailing
    // padding).
    var bridge_spans: std.ArrayList(source_map.Span) = .empty;
    defer bridge_spans.deinit(allocator);

    for (opts.bridge_js_chunks) |chunk| {
        try w.print("// --- bridge.js from {s} ---\n", .{chunk.origin});
        const start_byte = js_aw.written().len;
        try w.writeAll(chunk.source);
        const end_byte = js_aw.written().len;
        try w.writeAll("\n\n");
        try bridge_spans.append(allocator, .{
            .source = chunk.origin,
            .source_content = chunk.source,
            .start_byte = start_byte,
            .end_byte = end_byte,
        });
    }

    // __zunkLoad instantiates or swaps the WASM module. Called once during
    // startup, and again by __zunkHmrSwap when the dev server signals that
    // only the .wasm binary changed.
    try w.writeAll(
        \\// --- WASM load helper ---
        \\async function __zunkLoad(wasmUrl) {
        \\  const response = await fetch(wasmUrl);
        \\  const result = await WebAssembly.instantiateStreaming(response, { env });
        \\  instance = result.instance;
        \\  exports = instance.exports;
        \\  memory = exports.memory;
        \\
    );
    if (needs.handles) {
        try w.writeAll("  H._exports = exports;\n  H._memory = memory;\n");
    }
    if (needs.strings) {
        try w.writeAll("  readStr = (ptr, len) => new TextDecoder().decode(new Uint8Array(memory.buffer, ptr, len));\n");
    }
    try w.writeAll("  window.wasmBindings = exports;\n  window.wasmMemory = memory;\n");
    try w.writeAll("}\n\n");

    try w.print(
        \\await __zunkLoad('{s}{s}');
        \\
        \\
    , .{ opts.public_url, opts.wasm_filename });

    try emitFontLoad(w, opts.fonts);

    if (needs.webgpu_init) try emitWebGPUInit(w);

    if (has_init) {
        try w.writeAll("// Init\nexports.init();\n\n");
    }

    if (needs.render_loop) {
        try w.writeAll(
            \\// --- Render loop ---
            \\let zunkLastTime = 0;
            \\let zunkFrameId = 0;
            \\function zunkFrame(time) {
            \\  const dt = (time - zunkLastTime) / 1000;
            \\  zunkLastTime = time;
            \\
        );
        // Input flush is WASM-driven via input.poll() to avoid wiping per-frame state early.
        try w.writeAll(
            \\  exports.frame(Math.min(dt, 0.1));
            \\  zunkFrameId = requestAnimationFrame(zunkFrame);
            \\}
            \\zunkFrameId = requestAnimationFrame(zunkFrame);
            \\
            \\
        );
    }

    if (needs.resize_handler) {
        if (needs.webgpu_init) {
            try w.writeAll(
                \\// --- Resize handler (DPR-aware for WebGPU) ---
                \\function zunkResize() {
                \\  const c = document.getElementById('app') || document.querySelector('canvas');
                \\  const w = c ? c.clientWidth : window.innerWidth;
                \\  const h = c ? c.clientHeight : window.innerHeight;
                \\  if (c) {
                \\    const dpr = window.devicePixelRatio || 1;
                \\    c.width = Math.round(w * dpr);
                \\    c.height = Math.round(h * dpr);
                \\  }
                \\  exports.resize(w, h);
                \\}
                \\window.addEventListener('resize', zunkResize);
                \\(function zunkWatchDPR(){matchMedia(`(resolution:${window.devicePixelRatio}dppx)`).addEventListener('change',()=>{zunkResize();zunkWatchDPR();},{once:true})})();
                \\zunkResize();
                \\
                \\
            );
        } else {
            try w.writeAll(
                \\// --- Resize handler ---
                \\function zunkResize() {
                \\  const c = document.getElementById('app') || document.querySelector('canvas');
                \\  if (c) { c.width = window.innerWidth; c.height = window.innerHeight; }
                \\  exports.resize(window.innerWidth, window.innerHeight);
                \\}
                \\window.addEventListener('resize', zunkResize);
                \\zunkResize();
                \\
                \\
            );
        }
    }

    if (has_cleanup) {
        try w.writeAll("window.addEventListener('beforeunload', () => exports.cleanup());\n\n");
    }

    try emitHmrSwap(w, needs, has_init, has_cleanup);

    // window.wasmBindings / window.wasmMemory are (re)assigned inside
    // __zunkLoad so HMR keeps them pointed at the live module.
    try w.writeAll(
        \\// --- Startup event ---
        \\dispatchEvent(new CustomEvent('ZunkApplicationStarted', { detail: { wasm: instance, memory } }));
        \\
    );

    try w.writeAll("\n})();\n");

    // Build the source map BEFORE the header rewrite below so byte offsets
    // recorded in bridge_spans remain valid. The rewrite lengthens the
    // header but adds no newlines, so line numbers would be stable either
    // way -- but building here keeps the byte math unambiguous.
    const js_map: []const u8 = if (bridge_spans.items.len == 0)
        ""
    else
        try source_map.build(allocator, js_aw.written(), bridge_spans.items);
    errdefer if (js_map.len != 0) allocator.free(js_map);

    const full_hash = std.hash.XxHash3.hash(0, js_aw.written());
    var fingerprint: [8]u8 = undefined;
    std.mem.writeInt(u64, &fingerprint, full_hash, .big);
    const hex = std.fmt.bytesToHex(fingerprint, .lower);

    // Rewrite the placeholder header with the build fingerprint baked in. The
    // placeholder is the first thing written above, so its position is fixed.
    const old_header = "// Generated by zunk -- do not edit.\n// https://github.com/hotschmoe/zunk\n\n";
    const new_header = try std.fmt.allocPrint(allocator, "// Generated by zunk [build:{s}] -- do not edit.\n// https://github.com/hotschmoe/zunk\n\n", .{hex[0..8]});
    defer allocator.free(new_header);

    var js = js_aw.toArrayList();
    defer js.deinit(allocator);
    try js.replaceRange(allocator, 0, old_header.len, new_header);

    var html_aw: std.Io.Writer.Allocating = .init(allocator);
    defer html_aw.deinit();
    try generateHtml(&html_aw.writer, analysis, opts, categories_used);

    var report_aw: std.Io.Writer.Allocating = .init(allocator);
    defer report_aw.deinit();
    try generateReport(&report_aw.writer, analysis, resolutions, stub_count, hex[0..8], .{
        .verbose = opts.verbose_report,
        .json = opts.json_report,
    });

    return .{
        .js = try js.toOwnedSlice(allocator),
        .js_map = js_map,
        .html = try html_aw.toOwnedSlice(),
        .report = try report_aw.toOwnedSlice(),
        .js_hash = hex,
        .categories = categories_used,
    };
}

