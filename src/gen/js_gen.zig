        try w.print("\"build_fingerprint\":\"{s}\",", .{build_fingerprint});
        try w.print("\"total_imports\":{d},", .{analysis.imports.len});
        try w.print("\"total_exports\":{d},", .{analysis.exports.len});
        try w.print("\"stubs\":{d},", .{stub_count});
        try report_missing(w, analysis, resolutions, true);

        try w.writeAll("\"resolutions\":[");
        for (analysis.imports, 0..) |imp, i| {
            if (i > 0) try w.writeAll(",");
            const r = &resolutions[i];
            try w.writeAll("{\"module\":");
            try std.json.Stringify.value(imp.module, .{}, w);
            try w.writeAll(",\"name\":");
            try std.json.Stringify.value(imp.name, .{}, w);
            try w.print(",\"kind\":\"{s}\"", .{import_kinds[imp.kind]});
            try w.print(",\"confidence\":\"{s}\",\"category\":\"{s}\"", .{
                @tagName(r.confidence), @tagName(r.category),
            });
            if (r.confidence == .stub) {
                if (suggestMatch(imp.name)) |suggestion| {
                    try w.print(",\"suggestion\":\"{s}\"", .{suggestion});
                }
            }
            try w.writeAll("}");
        }
        try w.writeAll("],");

        try w.writeAll("\"categories\":{");
        var first_cat = true;
        for (std.enums.values(resolver.Category)) |cat| {
            const c = counts[@backingInt(cat)];
            if (c > 0) {
                if (!first_cat) try w.writeAll(",");
                try w.print("\"{s}\":{d}", .{ @tagName(cat), c });
                first_cat = false;
            }
        }
        try w.writeAll("},");

        try w.writeAll("\"lifecycle\":{");
        for (lifecycle_fns, 0..) |fname, li| {
            if (li > 0) try w.writeAll(",");
            try w.print("\"{s}\":{s}", .{
                fname, if (analysis.has_export(fname)) "true" else "false",
            });
        }
        try w.writeAll("}}");
        return;
    }

    try w.print("=== zunk binding resolution report === [build:{s}]\n\n", .{build_fingerprint});
    try w.print("Total imports: {d}\n", .{analysis.imports.len});
    try w.print("Total exports: {d}\n", .{analysis.exports.len});
    try w.print("Unresolved (stubs): {d}\n\n", .{stub_count});
    try report_missing(w, analysis, resolutions, false);

    if (stub_count > 0) {
        try w.writeAll("[red]WARNING: UNRESOLVED IMPORTS[/] -- these need a bridge.js or zunk naming convention:\n");
        for (analysis.imports, 0..) |imp, i| {
            if (resolutions[i].confidence == .stub) {
                try w.print("   [red]*[/] {s}.{s}", .{ imp.module, imp.name });
                if (analysis.get_import_signature(&imp)) |ft| {
                    try w.print(" (", .{});
                    for (ft.params, 0..) |p, j| {
                        if (j > 0) try w.print(", ", .{});
                        try w.print("{s}", .{@tagName(p)});
                    }
                    try w.print(") -> ", .{});
                    if (ft.returns.len == 0) {
                        try w.print("void", .{});
                    } else {
                        for (ft.returns, 0..) |r, j| {
                            if (j > 0) try w.print(", ", .{});
                            try w.print("{s}", .{@tagName(r)});
                        }
                    }
                }
                if (suggestMatch(imp.name)) |suggestion| {
                    try w.print(" [dim](did you mean: {s}?)[/]", .{suggestion});
                }
                try w.print("\n", .{});
            }
        }
        try w.writeAll("\nTo resolve these, either:\n");
        try w.writeAll("  1. Rename to use a zunk convention (e.g., ctx2d_fill_rect, audio_play)\n");
        try w.writeAll("  2. Provide a bridge.js file in your project root or js/ directory\n");
        try w.writeAll("  3. Use the Layer 2 web modules: @import(\"zunk\").web.*\n\n");
    }

    if (mode.verbose) {
        try w.writeAll("All resolutions:\n");
        for (std.enums.values(resolver.Category)) |cat| {
            if (counts[@backingInt(cat)] == 0) continue;
            try w.print("\n  [{s}] {s}:\n", .{ categoryColor(cat), @tagName(cat) });
            for (analysis.imports, 0..) |imp, i| {
                const r = &resolutions[i];
                if (r.category != cat) continue;
                const conf_color = confidenceColor(r.confidence);
                try w.print("    [{s}]{s}[/] {s}.{s}", .{
                    conf_color, @tagName(r.confidence), imp.module, imp.name,
                });
                if (r.description.len > 0) {
                    try w.print(" -- {s}", .{r.description});
                }
                try w.print("\n", .{});
            }
        }
        try w.writeAll("\n");
    }

    try w.writeAll("Resolved bindings by category:\n");
    for (std.enums.values(resolver.Category)) |cat| {
        const c = counts[@backingInt(cat)];
        if (c > 0) {
            try w.print("  [{s}]{s}[/]: {d}\n", .{ categoryColor(cat), @tagName(cat), c });
        }
    }

    try w.writeAll("\nLifecycle exports detected:\n");
    for (lifecycle_fns) |fname| {
        const found = analysis.has_export(fname);
        if (found) {
            try w.print("  [green]{s}[/]: yes\n", .{fname});
        } else {
            try w.print("  [dim]{s}[/]: no\n", .{fname});
        }
    }
}

const import_kinds = [_][]const u8{ "function", "table", "memory", "global" };

fn report_missing(
    w: *std.Io.Writer,
    analysis: *const wa.Analysis,
    resolutions: []const resolver.Resolution,
    json: bool,
) !void {
    assert(resolutions.len == analysis.imports.len);
    var count: u32 = 0;
    for (resolutions) |resolution| count += @intFromBool(resolution.confidence == .missing);
    assert(count <= analysis.imports.len);
    if (json) {
        try w.print("\"missing_imports\":{d},", .{count});
        return;
    }
    if (count == 0) return;
    try w.print("Missing imports (not supplied): {d}\n", .{count});
    for (analysis.imports, resolutions) |imp, resolution| {
        if (resolution.confidence != .missing) continue;
        assert(imp.kind < import_kinds.len);
        try w.print("  {s}.{s}: {s}; generated JS supplies only env functions\n", .{
            imp.module, imp.name, import_kinds[imp.kind],
        });
    }
    try w.writeAll("Provide these through the import object before instantiation.\n\n");
}

fn confidenceColor(conf: resolver.Confidence) []const u8 {
    return switch (conf) {
        .exact, .high => "green",
        .medium => "yellow",
        .low => "yellow",
        .stub, .missing => "red",
    };
}

fn categoryColor(cat: resolver.Category) []const u8 {
    return switch (cat) {
        .unknown => "red",
        .zunk_internal => "dim",
        else => "cyan",
    };
}

pub fn editDistance(a: []const u8, b: []const u8) usize {
    if (a.len == 0) return b.len;
    if (b.len == 0) return a.len;

    const max_len = 64;
    if (a.len > max_len or b.len > max_len) return max_len;

    var prev: [max_len + 1]usize = undefined;
    var curr: [max_len + 1]usize = undefined;

    for (0..b.len + 1) |j| prev[j] = j;

    for (a, 0..) |ca, i| {
        curr[0] = i + 1;
        for (b, 0..) |cb, j| {
            const cost: usize = if (ca == cb) 0 else 1;
            curr[j + 1] = @min(@min(curr[j] + 1, prev[j + 1] + 1), prev[j] + cost);
        }
        @memcpy(prev[0 .. b.len + 1], curr[0 .. b.len + 1]);
    }

    return prev[b.len];
}

fn suggestMatch(name: []const u8) ?[]const u8 {
    var best: ?[]const u8 = null;
    var best_dist: usize = 4; // threshold: must be <= 3

    for (resolver.exact_db) |entry| {
        const d = editDistance(name, entry.name);
        if (d < best_dist) {
            best_dist = d;
            best = entry.name;
        }
    }

    for (resolver.prefix_rules) |rule| {
        if (name.len > rule.prefix.len) {
            const d = editDistance(name[0..@min(name.len, rule.prefix.len)], rule.prefix);
            if (d <= 1 and d < best_dist) {
                best_dist = d;
                best = rule.prefix;
            }
        }
    }

    return best;
}
