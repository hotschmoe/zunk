fn writeEscaped(w: *std.Io.Writer, s: []const u8) !void {
    for (s) |c| switch (c) {
        '\\', '"' => {
            try w.writeByte('\\');
            try w.writeByte(c);
        },
        '\n', '\r' => try w.writeByte(' '),
        else => try w.writeByte(c),
    };
}

fn emitFontLoad(w: *std.Io.Writer, fonts: []const FontFace, blocking: bool) !void {
    if (fonts.len == 0) return;
    try w.writeAll(if (blocking)
        "// --- Fonts: the app starts once every face is loaded ---\nawait Promise.all([\n"
    else
        "// --- Fonts: loading in the background (the app does not wait) ---\nvoid Promise.all([\n");
    for (fonts) |f| {
        try w.print("  document.fonts.load(\"{d} 16px \\\"", .{f.weight});
        try writeEscaped(w, f.family);
        try w.writeAll("\\\"\"),\n");
    }
    try w.writeAll("].map(p => p.catch(e => console.warn('[zunk] font failed to load:', e))));\n\n");
}

fn emitFontFaces(w: *std.Io.Writer, public_url: []const u8, fonts: []const FontFace) !void {
    for (fonts) |f| {
        try w.writeAll("    @font-face { font-family: \"");
        try writeEscaped(w, f.family);
        try w.print("\"; font-weight: {d}; font-display: block; src: url(\"", .{f.weight});
        try writeEscaped(w, public_url);
        try w.writeAll("fonts/");
        try writeEscaped(w, f.file);
        try w.writeAll("\"); }\n");
    }
}

fn emitHmrSwap(w: *std.Io.Writer, needs: Features, has_init: bool, has_cleanup: bool) !void {
    try w.writeAll("async function __zunkHmrSwap(wasmUrl) {\n");
    try w.writeAll("  try {\n");

    if (needs.render_loop) {
        try w.writeAll("    if (zunkFrameId) { cancelAnimationFrame(zunkFrameId); zunkFrameId = 0; }\n");
    }
    if (has_cleanup) {
        try w.writeAll("    try { if (exports.cleanup) exports.cleanup(); } catch (e) { console.warn('[zunk hmr] cleanup threw:', e); }\n");
    }

    try w.writeAll(
        \\    let __zunkHmrSnapshot = null;
        \\    if (exports.__zunk_hmr_serialize && exports.__zunk_string_buf_ptr) {
        \\      const len = exports.__zunk_hmr_serialize();
        \\      if (len > 0) {
        \\        const ptr = exports.__zunk_string_buf_ptr();
        \\        __zunkHmrSnapshot = new Uint8Array(memory.buffer, ptr, len).slice();
        \\      }
        \\    }
        \\
        \\    await __zunkLoad(wasmUrl);
        \\
    );

    if (has_init) {
        try w.writeAll(
            \\    if (__zunkHmrSnapshot && exports.__zunk_hmr_hydrate && exports.__zunk_string_buf_ptr) {
            \\      const ptr = exports.__zunk_string_buf_ptr();
            \\      new Uint8Array(memory.buffer, ptr, __zunkHmrSnapshot.length).set(__zunkHmrSnapshot);
            \\      exports.__zunk_hmr_hydrate(ptr, __zunkHmrSnapshot.length);
            \\    } else if (exports.init) {
            \\      exports.init();
            \\    }
            \\
        );
    }

    if (needs.render_loop) {
        try w.writeAll(
            \\    if (exports.frame) {
            \\      zunkLastTime = performance.now();
            \\      zunkFrameId = requestAnimationFrame(zunkFrame);
            \\    }
            \\
        );
    }

    try w.writeAll(
        \\    console.info('[zunk hmr] swap complete');
        \\  } catch (err) {
        \\    console.error('[zunk hmr] swap failed, falling back to full reload:', err);
        \\    location.reload();
        \\  }
        \\}
        \\window.__zunkHmrSwap = __zunkHmrSwap;
        \\
        \\
    );
}

fn emitHandleTable(w: *std.Io.Writer) !void {
    try w.writeAll(
        \\const H = {
        \\  _table: new Map(),
        \\  _next: 1,
        \\  store(obj) { const id = this._next++; this._table.set(id, obj); return id; },
        \\  get(id) { return this._table.get(id); },
        \\  set(id, obj) { this._table.set(id, obj); },
        \\  release(id) { this._table.delete(id); },
        \\  nextId() { return this._next++; },
        \\};
        \\
        \\
    );
}

